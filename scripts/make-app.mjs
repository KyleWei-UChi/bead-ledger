/**
 * Builds "Bead Ledger.app" — a double-clickable launcher for the local app.
 *
 * The bundle is a thin wrapper, not a copy: it starts the data server from
 * this folder and opens the browser at it. Your data stays in data/beads.json
 * either way, so launching from the icon and running `npm start` are the same
 * app looking at the same file.
 *
 * Why an AppleScript applet rather than a bundle around a shell script: a
 * script has no Mach-O header, so Apple silicon assumes the app is Intel and
 * demands Rosetta before it will run (LaunchServices error -10669). osacompile
 * gives us Apple's own universal applet binary, which runs natively on arm64,
 * and the real work still lives in Resources/launch.sh.
 *
 * Usage: npm run app [-- --out <folder>]
 */
import { chmod, mkdir, rm, writeFile, copyFile, access } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';
import { homedir } from 'node:os';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const APP_NAME = 'Bead Ledger';
const PORT = Number(process.env.BEAD_API_PORT ?? 8787);

const args = process.argv.slice(2);
const outFlag = args.indexOf('--out');
const OUT_DIR = outFlag >= 0 && args[outFlag + 1]
  ? resolve(args[outFlag + 1])
  : join(homedir(), 'Applications');

const APP = join(OUT_DIR, `${APP_NAME}.app`);
const CONTENTS = join(APP, 'Contents');

// The launcher runs from Finder, which gives it a minimal PATH and none of
// your shell profile — so the node it should use is resolved now, at build
// time, with sensible fallbacks in case you later move or upgrade node.
const NODE_BIN = process.execPath;

const icns = join(ROOT, 'build', 'BeadLedger.icns');
try {
  await access(icns);
} catch {
  execFileSync(process.execPath, [join(ROOT, 'scripts', 'make-icon.mjs')], { stdio: 'inherit' });
}

const sh = (s) => `'${String(s).replace(/'/g, `'\\''`)}'`;

const launcher = `#!/bin/sh
# Generated by scripts/make-app.mjs — re-run 'npm run app' after moving the project.
set -u

PROJECT=${sh(ROOT)}
NODE=${sh(NODE_BIN)}
PORT=${PORT}
URL="http://127.0.0.1:$PORT"
LOG="$PROJECT/data/server.log"

say() { /usr/bin/osascript -e "display notification \\"$1\\" with title \\"${APP_NAME}\\"" >/dev/null 2>&1; }
fail() {
  /usr/bin/osascript -e "display dialog \\"$1\\" with title \\"${APP_NAME}\\" buttons {\\"OK\\"} default button 1 with icon stop" >/dev/null 2>&1
  exit 1
}

if [ ! -d "$PROJECT" ]; then
  fail "The project folder has moved or been renamed. Re-run 'npm run app' from its new location to rebuild this launcher."
fi

# Finder's PATH is minimal; put the chosen node first so npm and its scripts work.
if [ ! -x "$NODE" ]; then
  for candidate in /opt/homebrew/bin/node /usr/local/bin/node "$(command -v node 2>/dev/null)"; do
    if [ -n "$candidate" ] && [ -x "$candidate" ]; then NODE="$candidate"; break; fi
  done
fi
[ -x "$NODE" ] || fail "Node.js was not found. Install it from nodejs.org, then re-run 'npm run app'."
PATH="$(dirname "$NODE"):/usr/bin:/bin:/usr/sbin:/sbin"
export PATH

cd "$PROJECT" || fail "Could not open $PROJECT."
mkdir -p data

# Build when there is no build, or when the source is newer than one. This is
# checked before the running-server shortcut: the server serves dist/ from
# disk, so a rebuild alone is enough to pick up code changes.
needs_build=0
if [ -f dist/index.html ]; then
  newer=$(find src index.html vite.config.ts package.json tsconfig.json -newer dist/index.html -print -quit 2>/dev/null)
  [ -n "$newer" ] && needs_build=1
else
  needs_build=1
fi

if [ "$needs_build" = "1" ]; then
  if [ ! -d node_modules ]; then
    say "First run: installing dependencies…"
    npm install >>"$LOG" 2>&1 || fail "npm install failed. See data/server.log in the project folder."
  fi
  say "Building the latest version…"
  npm run build >>"$LOG" 2>&1 || fail "The build failed. See data/server.log in the project folder."
fi

# Already running? Then this is just "open my tracker".
if /usr/bin/curl -fsS --max-time 2 "$URL/api/health" >/dev/null 2>&1; then
  exec /usr/bin/open "$URL"
fi

say "Starting…"
nohup "$NODE" server/index.mjs >>"$LOG" 2>&1 &

# Wait for it to answer before handing over to the browser.
i=0
while [ $i -lt 60 ]; do
  if /usr/bin/curl -fsS --max-time 1 "$URL/api/health" >/dev/null 2>&1; then
    exec /usr/bin/open "$URL"
  fi
  /bin/sleep 0.25
  i=$((i + 1))
done

fail "The data server did not start within 15 seconds. The last lines of data/server.log:

$(tail -n 6 "$LOG" 2>/dev/null)"
`;

const applescript = `on run
	try
		with timeout of 900 seconds
			do shell script quoted form of ((POSIX path of (path to me)) & "Contents/Resources/launch.sh")
		end timeout
	end try
end run
`;

if (process.platform !== 'darwin') {
  console.error('This launcher is macOS-only. On other systems use `npm run build && npm start`.');
  process.exit(1);
}

const BUILD = join(ROOT, 'build');
await mkdir(BUILD, { recursive: true });
const source = join(BUILD, 'launcher.applescript');
await writeFile(source, applescript);

await rm(APP, { recursive: true, force: true });
await mkdir(OUT_DIR, { recursive: true });
execFileSync('/usr/bin/osacompile', ['-o', APP, source], { stdio: 'inherit' });

const launchScript = join(CONTENTS, 'Resources', 'launch.sh');
await writeFile(launchScript, launcher);
await chmod(launchScript, 0o755);

// The applet's icon file is Resources/applet.icns; swapping it is enough.
await copyFile(icns, join(CONTENTS, 'Resources', 'applet.icns'));

const plist = join(CONTENTS, 'Info.plist');

// osacompile ships its own icon in Assets.car and points CFBundleIconName at
// it, which would beat the applet.icns we just replaced. Drop the key so the
// icns wins, and drop the catalog so nothing stale is left behind.
try {
  execFileSync('/usr/bin/plutil', ['-remove', 'CFBundleIconName', plist], { stdio: 'ignore' });
} catch {}
await rm(join(CONTENTS, 'Resources', 'Assets.car'), { force: true });

// macOS gates ~/Desktop, ~/Documents and ~/Downloads behind a one-time
// prompt. The project sits in one of them, so the prompt is coming either
// way; these keys at least make it say what the app wants and why.
const why = `${APP_NAME} reads and writes your bead inventory in ${ROOT}.`;

for (const [key, type, value] of [
  ['CFBundleName', '-string', APP_NAME],
  ['CFBundleDisplayName', '-string', APP_NAME],
  ['CFBundleIdentifier', '-string', 'local.beadledger.launcher'],
  ['CFBundleShortVersionString', '-string', '1.0'],
  ['NSHighResolutionCapable', '-bool', 'true'],
  ['NSDesktopFolderUsageDescription', '-string', why],
  ['NSDocumentsFolderUsageDescription', '-string', why],
  ['NSDownloadsFolderUsageDescription', '-string', why],
]) {
  execFileSync('/usr/bin/plutil', ['-replace', key, type, value, plist]);
}

// Editing the bundle invalidates the signature osacompile left, and unsigned
// bundles get a rougher ride on Apple silicon, so sign it ad-hoc again.
try {
  execFileSync('/usr/bin/codesign', ['--force', '--deep', '--sign', '-', APP], { stdio: 'ignore' });
} catch {}

// Nudge Finder and Spotlight to pick up the new bundle and its icon.
try {
  execFileSync('/usr/bin/touch', [APP]);
} catch {}

await rm(source, { force: true });

console.log(`\n  ${APP_NAME}.app → ${APP}`);
console.log('  Double-click it, or drag it to the Dock.');
console.log(`  It serves ${ROOT} on http://127.0.0.1:${PORT}\n`);
